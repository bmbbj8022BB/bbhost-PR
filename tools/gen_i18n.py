#!/usr/bin/env python3
"""ko_dict.py + the keys the sources use -> lang/ko.po and src/host/i18n_ko.inc. Usage: gen_i18n.py repo_dir src files..."""
import sys, os, json, importlib.util
sys.path.insert(0, os.path.dirname(__file__))
import extract_keys
from ko_dict import KO
repo = sys.argv[1]; files = sys.argv[2:]
used = []
for f in files:
    for k in extract_keys.keys(os.path.join(repo, f)):
        if k not in used: used.append(k)
skip = {'OK  %s', '!   %s', '[%s]', 'server.example.com', '%s.'}
missing = [k for k in used if k not in KO and k not in skip]
unused = [k for k in KO if k not in used]
print('keys used:', len(used), 'dictionary:', len(KO))
print('MISSING translations:', len(missing))
for k in missing: print('   ', repr(k))
print('in dictionary but not found as tr()/trl()/tf() literal (extras or typos):', len(unused))
for k in unused: print('   ', repr(k)[:110])
def esc(s): return s.replace('\\','\\\\').replace('"','\\"').replace('\n','\\n').replace('\t','\\t')
os.makedirs(os.path.join(repo,'lang'), exist_ok=True)
with open(os.path.join(repo,'lang','ko.po'),'w',encoding='utf-8') as po:
    po.write('# Korean (ko) for bbhost. msgid is the English text in the source; msgstr is shown instead.\n# Keep every %s / %d / %llu / %.0f in the same order. Put an edited copy at <bbhost folder>/lang/ko.po to override this table without rebuilding.\n\n')
    for k,v in KO.items():
        po.write(f'msgid "{esc(k)}"\nmsgstr "{esc(v)}"\n\n')
with open(os.path.join(repo,'src','host','i18n_ko.inc'),'w',encoding='utf-8') as inc:
    inc.write('// Generated by tools/gen_i18n.py from lang/ko.po; do not edit by hand.\n')
    for k,v in KO.items():
        inc.write(f'    {{"{esc(k)}", "{esc(v)}"}},\n')
